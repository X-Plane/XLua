#!/usr/bin/env python3
"""Write a weak no-op definition for each XPLM_API function in the XPLM headers.

Usage: gen_xplm_stubs.py <XPLM header dir> <output .cpp> <compiler> [compiler flags...]

The test program links all of XLua, so it needs a definition of each XPLM
function that XLua can call. A weak definition does nothing and returns zero.
fake_xplm.cpp gives a normal (strong) definition for the functions that the
tests need, and the linker then uses that definition instead.

The script runs the C preprocessor over all headers, so that only the
functions that the compiler sees are written. With XPLM defined, XPLM_API
expands to a visibility attribute, which marks each declaration.
"""
import os
import re
import subprocess
import sys

header_dir, out_path, compiler = sys.argv[1], sys.argv[2], sys.argv[3]
flags = sys.argv[4:]

headers = sorted(f for f in os.listdir(header_dir) if f.endswith('.h'))
source = ''.join(f'#include "{h}"\n' for h in headers)
result = subprocess.run([compiler, '-E', '-P', '-x', 'c++', '-DXPLM=1', '-I', header_dir] + flags + ['-'],
                        input=source, capture_output=True, text=True)
if result.returncode != 0:
    sys.exit('gen_xplm_stubs.py: the preprocessor failed:\n' + result.stderr)
text = result.stdout
text = re.sub(r'\s+', ' ', text)

marker = '__attribute__((visibility("default")))'
lines = ['// Generated by gen_xplm_stubs.py. Do not edit.', '', '#define XPLM 1']
lines += [f'#include "{h}"' for h in headers]
lines.append('')
names = set()
for decl in text.split(';'):
    i = decl.find(marker)
    if i < 0:
        continue
    m = re.match(r'(.*?)\b(XPLM\w+)\s*\((.*)\)\s*$', decl[i + len(marker):].strip())
    if not m:
        sys.exit(f'gen_xplm_stubs.py: cannot read the declaration "{decl.strip()}"')
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
    if name in names:
        continue
    names.add(name)
    body = '' if ret == 'void' else ' return {}; '
    lines.append(f'__attribute__((weak)) {ret} {name}({params}) {{{body}}}')

if len(names) < 300:
    sys.exit(f'gen_xplm_stubs.py: found only {len(names)} functions; the header format changed')

with open(out_path, 'w') as f:
    f.write('\n'.join(lines) + '\n')
